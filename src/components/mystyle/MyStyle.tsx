"use client";

import { useEffect, useState } from "react";
import Link from "next/link";
import { DayFlatLay } from "@/components/planner/DayFlatLay";
import { ArrowRightIcon, PaletteIcon } from "@/components/Icons";
import { PageShell, btnPrimary, btnSecondary } from "@/components/ui";
import { byLatestTryOn, type ClothingItem, type Outfit } from "@/components/OutfitCard";
import type { PlanDays } from "@/lib/planOutfits";
import type { StyleProfile } from "@/lib/styleProfile";

const pad2 = (n: number) => String(n).padStart(2, "0");
const ymd = (d: Date) => `${d.getFullYear()}-${pad2(d.getMonth() + 1)}-${pad2(d.getDate())}`;
const card = "rounded-[22px] bg-white shadow-[0_1px_0_rgba(18,24,33,0.03),0_14px_36px_rgba(18,30,45,0.06)]";

function SectionHead({ id, title, href, link }: { id: string; title: string; href: string; link: string }) {
  return (
    <div className="mb-3 flex items-baseline justify-between gap-3">
      <h2 id={id} className="font-display text-[28px] leading-none text-[#121821]">
        {title}
      </h2>
      <Link href={href} className="group inline-flex shrink-0 items-center gap-1 text-[12.5px] font-semibold text-[#121821]">
        {link} <ArrowRightIcon className="h-4 w-4 transition-transform group-hover:translate-x-0.5" />
      </Link>
    </div>
  );
}

/**
 * My Style, Virm's first page: what's yours. Your saved outfits, today's outfit from the Planner, and your AI Stylist
 * profile. Everything here is read from what you already have; nothing is generated by AI and nothing is paid.
 */
export function MyStyle() {
  const [closet, setCloset] = useState<ClothingItem[] | null>(null);
  useEffect(() => {
    let gone = false;
    fetch("/api/closet/items", { cache: "no-store" })
      .then(async (res) => (res.ok ? ((await res.json()) as { items: ClothingItem[] }).items : null))
      .then((items) => !gone && setCloset(items ?? []))
      .catch(() => !gone && setCloset([]));
    return () => {
      gone = true;
    };
  }, []);

  return (
    <main className="flex-1 pb-20">
      <PageShell className="max-w-3xl! pt-8">
        <h1 className="font-display text-[44px] leading-none text-[#121821]">My Style</h1>
        <SavedOutfits />
        {closet && closet.length >= 2 && <TodayOutfit closet={closet} />}
        <Stylist />
      </PageShell>
    </main>
  );
}

/** Your saved outfits, newest try-ons first (the try-on picture when there is one, else the pieces). */
function SavedOutfits() {
  const [saved, setSaved] = useState<Outfit[] | null>(null);
  useEffect(() => {
    let gone = false;
    fetch("/api/outfits", { cache: "no-store" })
      .then(async (res) => (res.ok ? ((await res.json()) as { outfits: Outfit[] }).outfits : []))
      .then((list) => !gone && setSaved(list.filter((o) => o.isFavorite).sort(byLatestTryOn)))
      .catch(() => !gone && setSaved([]));
    return () => {
      gone = true;
    };
  }, []);

  if (saved === null) return <div className={`${card} mt-8 h-48 animate-pulse`} />;
  return (
    <section aria-labelledby="saved-title" className="mt-8">
      <SectionHead id="saved-title" title="Saved outfits" href="/outfits/saved" link="See all" />
      {saved.length === 0 ? (
        <p className={`${card} p-5 text-[13.5px] text-[#4f5b66]`}>Outfits you save show up here.</p>
      ) : (
        <ul className="-mx-5 flex snap-x gap-3 overflow-x-auto px-5 pb-2 [scrollbar-width:none] sm:mx-0 sm:grid sm:grid-cols-4 sm:overflow-visible sm:px-0 [&::-webkit-scrollbar]:hidden">
          {saved.slice(0, 8).map((o) => {
            const pieces = o.layers.flatMap((l) => l.items);
            return (
              <li key={o.id} className="w-[38vw] max-w-[170px] shrink-0 snap-start sm:w-auto sm:max-w-none">
                <Link href="/outfits/saved" className={`${card} group block aspect-[3/4] overflow-hidden`}>
                  {o.tryOn ? (
                    // eslint-disable-next-line @next/next/no-img-element -- the person's own try-on picture
                    <img
                      src={`/api/outfits/${o.id}/try-on/image?v=${o.tryOn}`}
                      alt={o.occasion ?? "Saved outfit"}
                      loading="lazy"
                      className="h-full w-full object-cover object-top transition-transform duration-500 group-hover:scale-[1.03]"
                    />
                  ) : (
                    <span className="block h-full p-2">
                      <DayFlatLay pieces={pieces} />
                    </span>
                  )}
                </Link>
                {o.occasion && <span className="mt-1.5 block truncate text-[12px] font-medium capitalize text-[#4f5b66]">{o.occasion}</span>}
              </li>
            );
          })}
        </ul>
      )}
    </section>
  );
}

/**
 * Today's outfit, from the Planner: Swap asks the Planner for another free suggestion for today and keeps it; See the
 * month opens the Planner on its month. With nothing planned, one free suggestion for today.
 */
function TodayOutfit({ closet }: { closet: ClothingItem[] }) {
  const [today] = useState(() => ymd(new Date()));
  const [ids, setIds] = useState<string[] | null>(null);
  const [busy, setBusy] = useState(false);
  const [problem, setProblem] = useState<string | null>(null);

  useEffect(() => {
    let gone = false;
    fetch(`/api/planner?month=${today.slice(0, 7)}`, { cache: "no-store" })
      .then(async (res) => (res.ok ? ((await res.json()) as { days: PlanDays }).days : {}))
      .then((days) => !gone && setIds(days[today]?.items ?? []))
      .catch(() => !gone && setIds([]));
    return () => {
      gone = true;
    };
  }, [today]);

  const byId = new Map(closet.map((p) => [p.id, p]));
  const pieces = (ids ?? []).flatMap((id) => byId.get(id) ?? []);

  /** A new free suggestion for today (never the same as the one now), kept in the Planner. */
  async function suggest() {
    setBusy(true);
    setProblem(null);
    const post = (body: unknown) =>
      fetch("/api/planner/day", { method: "POST", headers: { "content-type": "application/json" }, body: JSON.stringify(body) })
        .then(async (res) => ({ ok: res.ok, data: (await res.json().catch(() => ({}))) as { items?: string[]; error?: string } }))
        .catch(() => ({ ok: false, data: {} as { items?: string[]; error?: string } }));
    const made = await post({ date: today, generate: true, current: ids ?? [] });
    if (!made.ok || !made.data.items?.length) {
      setProblem(made.data.error ?? "Couldn't make a new outfit right now.");
      return setBusy(false);
    }
    const saved = await post({ date: today, items: made.data.items, source: "chosen" });
    if (saved.ok) setIds(made.data.items);
    else setProblem("Couldn't keep that outfit. Please try again.");
    setBusy(false);
  }

  if (ids === null) return <div className={`${card} mt-10 h-48 animate-pulse`} />;
  return (
    <section aria-labelledby="today-title" className="mt-10">
      <SectionHead id="today-title" title="Planner" href="/planner" link="See the month" />
      <div className={`${card} flex items-center gap-4 p-4`}>
        <div className="aspect-[4/5] w-[42%] max-w-[200px] shrink-0 overflow-hidden rounded-[16px] bg-[#f6f5f2] p-2">
          {pieces.length > 0 ? <DayFlatLay pieces={pieces} /> : <div className="grid h-full place-items-center text-center text-[12px] text-[#8a949e]">Nothing planned yet</div>}
        </div>
        <div className="flex min-w-0 flex-1 flex-col gap-2">
          <p className="text-[11px] font-semibold uppercase tracking-[1.8px] text-[#5d6874]">Today</p>
          {pieces.length > 0 ? (
            <>
              <p className="text-[13px] text-[#4f5b66]">{pieces.map((p) => p.description.split(/[,;(]/)[0]).slice(0, 3).join(" · ")}</p>
              <button onClick={suggest} disabled={busy} className={`${btnSecondary} min-h-[44px]`}>
                {busy ? "Finding one…" : "Swap"}
              </button>
            </>
          ) : (
            <button onClick={suggest} disabled={busy} className={`${btnPrimary} min-h-[44px]`}>
              {busy ? "Finding one…" : "Suggest one"}
            </button>
          )}
          {problem && (
            <p role="alert" className="text-[12px] text-[#a1312a]">
              {problem}
            </p>
          )}
        </div>
      </div>
    </section>
  );
}

/** Your AI Stylist profile at a glance (your season, colors and style), or the way to start it. Read only. */
function Stylist() {
  const [profile, setProfile] = useState<StyleProfile | null | undefined>(undefined);
  useEffect(() => {
    let gone = false;
    fetch("/api/studio", { cache: "no-store" })
      .then(async (res) => (res.ok ? ((await res.json()) as { profile?: StyleProfile }).profile : undefined))
      .then((p) => !gone && setProfile(p && p.sources.length ? p : null))
      .catch(() => !gone && setProfile(null));
    return () => {
      gone = true;
    };
  }, []);

  if (profile === undefined) return <div className={`${card} mt-10 h-40 animate-pulse`} />;
  return (
    <section aria-labelledby="stylist-title" className="mt-10">
      <SectionHead id="stylist-title" title="AI Stylist" href="/stylist" link="Open" />
      {profile ? (
        <Link href="/stylist" className={`${card} block p-5`}>
          {profile.color && (
            <p className="font-display text-[24px] leading-tight text-[#121821]">
              {profile.color.season}
              <span className="ml-2 align-middle text-[12.5px] font-normal text-[#5d6874]">{profile.color.undertone} undertone</span>
            </p>
          )}
          {profile.color?.best.length ? (
            <ul aria-label="Your colors" className="mt-3 flex flex-wrap gap-1.5">
              {profile.color.best.slice(0, 8).map((c) => (
                <li key={c.hex} title={c.name} className="h-7 w-7 rounded-full shadow-[inset_0_0_0_1px_rgba(18,24,33,0.12)]" style={{ background: c.hex }} />
              ))}
            </ul>
          ) : null}
          {profile.style && (
            <p className="mt-3 text-[13.5px] leading-snug text-[#26313a]">
              <span className="font-semibold">{profile.style.aesthetic || "Your style"}</span>
              {profile.style.keywords.length ? <span className="text-[#5d6874]"> · {profile.style.keywords.slice(0, 4).join(", ")}</span> : null}
            </p>
          )}
          {!profile.color && !profile.style && <p className="text-[13.5px] text-[#4f5b66]">See your reports and Style Profile.</p>}
        </Link>
      ) : (
        <Link href="/stylist" className={`${card} flex items-center gap-4 p-5`}>
          <span className="grid h-12 w-12 shrink-0 place-items-center rounded-[14px] bg-[#121821] text-white">
            <PaletteIcon className="h-[22px] w-[22px]" />
          </span>
          <span className="min-w-0">
            <span className="block text-[15.5px] font-semibold text-[#121821]">Discover your colors</span>
            <span className="block text-[12.5px] text-[#5d6874]">Your season, makeup, hair and style, from one photo</span>
          </span>
        </Link>
      )}
    </section>
  );
}
